#!/usr/bin/env python3
"""Builds src/recomp/access_sounds.inc, the recorded audio cues, from data/access_sounds/.

    uv run --with soundfile --with numpy python tools/access/make_sounds.py

The recordings are Kenney's (CC0, data/access_sounds/Kenney-License.txt). Each cue is mono, 48 kHz,
16 bit, stored as a C array so the program needs no extra files. The game's direction pitch (higher
ahead, level at the sides, lower behind) is applied when a cue plays, on top of what is done here.
"""
from pathlib import Path

import numpy as np
import soundfile as sf

ROOT = Path(__file__).resolve().parents[2]
SRC = ROOT / "data" / "access_sounds"
OUT = ROOT / "src" / "recomp" / "access_sounds.inc"
RATE = 48000


def load(name: str) -> np.ndarray:
    d, r = sf.read(SRC / name, dtype="float64")
    if d.ndim > 1:
        d = d.mean(axis=1)
    return resample(d, r / RATE)


def resample(d: np.ndarray, step: float) -> np.ndarray:
    """Reads d at step samples per output sample: below 1 slows it down and lowers it."""
    pos = np.arange(0.0, len(d) - 1, step)
    i = pos.astype(int)
    f = pos - i
    return d[i] * (1 - f) + d[i + 1] * f


def fade(d: np.ndarray, ms_in: float, ms_out: float) -> np.ndarray:
    d = d.copy()
    a, b = int(RATE * ms_in / 1000), int(RATE * ms_out / 1000)
    if a:
        d[:a] *= np.linspace(0, 1, a)
    if b:
        d[-b:] *= np.linspace(1, 0, b)
    return d


def trim(d: np.ndarray, floor: float = 0.02) -> np.ndarray:
    loud = np.nonzero(np.abs(d) > floor * np.abs(d).max())[0]
    return d[max(loud[0] - 48, 0):loud[-1] + 1]


def normalize(d: np.ndarray, peak: float = 0.9) -> np.ndarray:
    return d * (peak / max(np.abs(d).max(), 1e-9))


def horse() -> np.ndarray:
    """A creaking door, slowed to a heavy wooden rock: the rocking horse."""
    d = trim(load("creak1.ogg"))
    d = resample(d, 0.7)  # 70 percent speed: slower and lower
    d = d[: int(RATE * 0.8)]
    return normalize(fade(d, 5, 120))


def door() -> np.ndarray:
    """The same creak at its own speed: a door. The horse's is slower and lower, so they differ."""
    d = trim(load("creak1.ogg"))[: int(RATE * 0.55)]
    return normalize(fade(d, 5, 100))


def step() -> np.ndarray:
    """A footstep on wood: stepping on or off a moving floor (played higher for on, lower for off)."""
    return normalize(fade(trim(load("footstep_wood_001.ogg")), 2, 30))


def ride() -> np.ndarray:
    """A soft wooden clack, repeated while a moving floor carries Luigi."""
    return normalize(fade(trim(load("impactWood_light_002.ogg")), 2, 30), 0.6)


def key() -> np.ndarray:
    """A light metal tink: keys."""
    return normalize(fade(trim(load("impactMetal_light_001.ogg")), 2, 40))


def coin() -> np.ndarray:
    """The keys' tink raised a fifth, so coins and bills sound alike but apart."""
    return normalize(fade(trim(resample(load("impactMetal_light_001.ogg"), 1.5)), 2, 30))


def bounce() -> np.ndarray:
    """A soft thump, raised a little and repeated as a ball's bounces settle."""
    hit = trim(resample(load("impactSoft_medium_000.ogg"), 1.25))
    hits = [(0.0, 1.0), (0.17, 0.62), (0.29, 0.4), (0.37, 0.24)]
    out = np.zeros(int(RATE * (hits[-1][0] + 0.02)) + len(hit))
    for at, gain in hits:
        s = int(RATE * at)
        out[s:s + len(hit)] += hit * gain
    return normalize(fade(out, 2, 40))


def emit(f, name: str, d: np.ndarray) -> None:
    v = np.clip(np.round(d * 32767), -32768, 32767).astype(np.int16)
    f.write(f"constexpr std::int16_t k{name}[] = {{\n")
    for i in range(0, len(v), 16):
        f.write("    " + ", ".join(str(int(x)) for x in v[i:i + 16]) + ",\n")
    f.write("};\n")


def main() -> None:
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("// Generated by tools/access/make_sounds.py from data/access_sounds/ (Kenney, CC0). Do not edit.\n")
        f.write(f"// Mono, {RATE} Hz, 16 bit.\n")
        emit(f, "HorseCreak", horse())
        emit(f, "DoorCreak", door())
        emit(f, "BallBounce", bounce())
        emit(f, "KeyTink", key())
        emit(f, "CoinTink", coin())
        emit(f, "PlatformStep", step())
        emit(f, "PlatformRide", ride())
    print(f"wrote {OUT}")


if __name__ == "__main__":
    main()
